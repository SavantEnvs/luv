assert(uv.fs_open("/dev/stdin", "r", 438) == nil)
assert(uv.fs_open("/dev/null", "r", 438) == nil)
uv.fs_open("/dev/zero", "r", 438, function(err, fd) assert(err and fd == nil) end)
local fd = uv.fs_open("/etc/hostname", "r", 438)
local s = uv.fs_read(fd, 1e13, 0)
assert(type(s) == "string")
uv.fs_read(fd, 0x7fffffff, 0, function(e, d) end)
local d = uv.fs_open("/etc", "r", 438)
assert(d and uv.fs_fstat(d).type == "directory")
uv.fs_close(d)
uv.fs_close(fd)
uv.run()
